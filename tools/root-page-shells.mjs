export function renderRootHeader({ active, language }) {
    const links = navigation.map(([key, href, labels]) => {
        const activeClass = key === active ? ' active' : '';
        const label = labels[language];
        return `                    <li><a href="${href}" class="nav-link${activeClass}" data-i18n="nav.${key}" title="${labels.en}">${label}</a></li>`;
    }).join('\n');

    const logo = language === 'zh' ? '周婧 | 艺术家' : '';
    const languageLabel = language === 'zh' ? 'EN' : '';
    return `    <!-- BEGIN:ROOT_HEADER (generated by npm run sync:shells) -->
    <header class="header">
        <nav class="nav-container">
            <div class="logo" data-i18n="home.title">${logo}</div>
            <button type="button" class="mobile-menu-toggle" data-i18n-aria="nav.menu" aria-label="Menu" aria-controls="primary-navigation" aria-expanded="false">
                <span></span>
                <span></span>
                <span></span>
            </button>
            <div class="nav-right" id="primary-navigation">
                <ul class="nav-links">
${links}
                </ul>
                <button type="button" class="lang-toggle" aria-label="Switch language">
                    <span class="lang-text" data-i18n="lang.current">${languageLabel}</span>
                    <i class="fas fa-globe"></i>
                </button>
            </div>
        </nav>
    </header>
    <!-- END:ROOT_HEADER -->`;
}

